// 初始化牌組
// ══════════════════════════════════════
function generateDeck(excludeMonarchs = false) {
    let deck = [];
    let characters = cardDatabase.filter(c => c.type !== "計策" && c.type !== "突發事件" && c.type !== "陣法" && c.type !== "裝備");
    if (excludeMonarchs) {
        characters = characters.filter(c => c.type !== "聖人");
    }
    const actions    = cardDatabase.filter(c => (c.type === "計策" || c.type === "突發事件" || c.isBasic) && !c.formation);
    const formations = cardDatabase.filter(c => c.type === "陣法");
    const equipments = cardDatabase.filter(c => c.type === "裝備");

    // 放入人物（24張）
    for (let i = 0; i < 24; i++) {
        deck.push({ ...characters[Math.floor(Math.random() * characters.length)], uid: Math.random().toString(36).substr(2, 9) });
    }
    // 放入計策與基本卡（24張）
    for (let i = 0; i < 24; i++) {
        deck.push({ ...actions[Math.floor(Math.random() * actions.length)], uid: Math.random().toString(36).substr(2, 9) });
    }
    // 放入陣法卡（4張）
    for (let i = 0; i < 4; i++) {
        deck.push({ ...formations[Math.floor(Math.random() * formations.length)], uid: Math.random().toString(36).substr(2, 9) });
    }
    // 放入裝備卡（2張）
    for (let i = 0; i < 2; i++) {
        deck.push({ ...equipments[Math.floor(Math.random() * equipments.length)], uid: Math.random().toString(36).substr(2, 9) });
    }

    // Fisher-Yates 洗牌
    for (let i = deck.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [deck[i], deck[j]] = [deck[j], deck[i]];
    }
    return deck;
}

